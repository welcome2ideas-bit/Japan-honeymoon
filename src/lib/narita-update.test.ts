import { expect, it } from 'vitest';
import { parseTrip } from './import';
import { connectItinerary } from './confirmed-travel';
import { updateCatalog } from './catalog-update';
import settings from '../../data/trip.json';
import places from '../../data/places.json';
import itinerary from '../../data/itinerary.json';
import hotels from '../../data/hotels.json';
import transport from '../../data/transport.json';
import tasks from '../../data/checklist.json';
const fresh=()=>parseTrip(structuredClone({version:2,settings,places,itinerary,hotels,transport,tasks,wishlist:[]}));
it('keeps the NEX departure confirmed without treating the approximate alighting time as exact',()=>{
 const d=fresh(),t=d.transport.find(t=>t.id==='narita-express')!;
 expect(t).toMatchObject({status:'Confirmado',time:'13:08',departureAt:'2026-12-03T13:08:00+09:00',departureTimeZone:'Asia/Tokyo',arrivalAt:null,arrivalTime:null});
 expect(t.seat).toContain('Vagón 3 · 13A y 13B');expect(t.note).toContain('6.660 JPY');
 expect(t.note).toContain('Terminal 1, llegada 14:31 confirmada');expect(t.title).toContain('BAJARSE EN TERMINAL 2·3');
 const day=connectItinerary(d).find(d=>d.date==='2026-12-03')!;
 expect(day.activities.find(a=>a.transportId===t.id)?.start).toBe(t.departureAt);
 const stop=day.activities.find(a=>a.id==='2026-12-03-alight-t23')!;
 expect(stop.start).toBeNull();expect(stop.planningNote).toContain('14:27 · Llegada aproximada');
 expect(day.activities.find(a=>a.id==='2026-12-03-leave-hotel')?.planningNote).toContain('11:45');
 expect(day.activities.find(a=>a.id==='2026-12-03-v24-3')).toMatchObject({title:'Comida',start:null});
 expect(day.activities.find(a=>a.id==='2026-12-03-v24-3')?.planningNote).not.toContain('12:00');
 expect(new Set(day.activities.map(a=>a.id)).size).toBe(day.activities.length);
 expect(d.transport.find(t=>t.id==='transport-10')).toMatchObject({departureAt:'2026-12-03T18:30:00+09:00',arrivalAt:'2026-12-03T22:55:00+08:00'});
 expect(d.transport.find(t=>t.id==='flight-hkg-madrid')).toMatchObject({departureAt:'2026-12-04T00:45:00+08:00',arrivalAt:'2026-12-04T08:35:00+01:00'});
});
it('reuses the purchase task as pending pickup only once and retains personal data',()=>{
 const old=fresh();old.catalogRevision=7;
 old.tasks.find(t=>t.id==='v24-task-12')!.status='Completado';
 old.tasks.push({id:'personal',title:'Mi tarea',category:'Personal',status:'Reservado',note:'Mi nota'});
 old.deletedTaskIds=['v24-task-16'];old.places[0].favorite=true;old.places[0].note='Favorito';
 old.itinerary[0].activities[0].completed=true;
 const next=updateCatalog(old,fresh());
 expect(next.tasks.find(t=>t.id==='v24-task-12')).toMatchObject({status:'Pendiente',recommendedDate:'2026-11-30',category:'Recogidas importantes'});
 expect(next.tasks.filter(t=>/Comprar.*(?:N.EX|Narita)/i.test(t.title))).toHaveLength(0);
 expect(next.tasks.find(t=>t.id==='personal')).toEqual(old.tasks.find(t=>t.id==='personal'));
 expect(next.tasks.some(t=>t.id==='v24-task-16')).toBe(false);
 expect(next.places[0]).toMatchObject({favorite:true,note:'Favorito'});
 expect(next.itinerary[0].activities[0].completed).toBe(true);expect(next.wishlist).toEqual(old.wishlist);
 const pickup=next.itinerary.find(d=>d.date==='2026-11-30')!.activities.filter(a=>a.id==='2026-11-30-nex-pickup');
 expect(pickup).toHaveLength(1);expect(pickup[0].planningNote).toContain('16:30');expect(pickup[0].start).toBeNull();
 next.tasks.find(t=>t.id==='v24-task-12')!.status='Completado';
 expect(updateCatalog(next,fresh())).toBe(next);
});
